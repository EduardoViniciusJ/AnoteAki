//! Note queries (PRD §12). All input is validated here,
//! and all SQL is parameterized.

use rusqlite::{Connection, OptionalExtension, Row, params};
use serde::Serialize;

use crate::error::AppError;

/// `body` limit, in characters (PRD §12, open decision 4).
pub const BODY_MAX_CHARS: usize = 100_000;
pub const TITLE_MAX_CHARS: usize = 80;
pub const PREVIEW_MAX_CHARS: usize = 140;
pub const QUERY_MAX_CHARS: usize = 200;
pub const LIMIT_DEFAULT: i64 = 50;
pub const LIMIT_MAX: i64 = 200;
pub const HEADING_MAX_CHARS: usize = 200;
pub const STICKER_COLORS: [&str; 6] = ["yellow", "pink", "blue", "green", "lilac", "paper"];
/// Background opacity levels, in percent.
pub const OPACITIES: [i64; 3] = [100, 85, 70];

/// ISO 8601 UTC with milliseconds, generated by SQLite itself (PRD §12).
const NOW: &str = "strftime('%Y-%m-%dT%H:%M:%fZ','now')";

/// Only the start of the body is read to build the list preview.
const PREVIEW_SOURCE_CHARS: usize = 2_000;

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Note {
    pub id: i64,
    pub title: String,
    pub heading: String,
    pub body: String,
    pub color: Option<String>,
    pub opacity: i64,
    pub pinned: bool,
    pub created_at: String,
    pub updated_at: String,
    pub deleted_at: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct NoteSummary {
    pub id: i64,
    pub title: String,
    pub preview: String,
    pub color: Option<String>,
    pub pinned: bool,
    pub updated_at: String,
    pub deleted_at: Option<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Scope {
    Active,
    Trash,
}

impl Scope {
    pub fn parse(value: &str) -> Result<Self, AppError> {
        match value {
            "active" => Ok(Self::Active),
            "trash" => Ok(Self::Trash),
            _ => Err(AppError::InvalidInput("Escopo inválido.")),
        }
    }
}

/// `sort` of `list_notes`. Only how the list is ordered; pinned notes
/// still come first in the active scope.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Sort {
    Updated,
    Created,
    Title,
}

impl Sort {
    pub fn parse(value: Option<&str>) -> Result<Self, AppError> {
        match value {
            None | Some("updated") => Ok(Self::Updated),
            Some("created") => Ok(Self::Created),
            Some("title") => Ok(Self::Title),
            Some(_) => Err(AppError::InvalidInput("Ordenação inválida.")),
        }
    }

    /// SQL sort keys. Title sort is case-insensitive, untitled notes last
    /// (only possible in the trash; `active` already excludes them).
    fn order_sql(self) -> &'static str {
        match self {
            Self::Updated => "updated_at DESC, id DESC",
            Self::Created => "created_at DESC, id DESC",
            Self::Title => "title = '', title COLLATE NOCASE ASC, id ASC",
        }
    }
}

const NOTE_COLUMNS: &str =
    "id, title, heading, body, color, opacity, pinned, created_at, updated_at, deleted_at";

fn note_from_row(row: &Row<'_>) -> rusqlite::Result<Note> {
    Ok(Note {
        id: row.get(0)?,
        title: row.get(1)?,
        heading: row.get(2)?,
        body: row.get(3)?,
        color: row.get(4)?,
        opacity: row.get(5)?,
        pinned: row.get(6)?,
        created_at: row.get(7)?,
        updated_at: row.get(8)?,
        deleted_at: row.get(9)?,
    })
}

/// Input of `save`. `None` fields keep the current value on update.
#[derive(Debug, Default, Clone, Copy)]
pub struct SaveInput<'a> {
    pub id: Option<i64>,
    pub body: &'a str,
    pub heading: Option<&'a str>,
    pub color: Option<&'a str>,
    pub opacity: Option<i64>,
}

/// Columns for `summary_from_row`, with the body cut in SQL (a note can have 100k chars).
fn summary_columns(table: &str) -> String {
    format!(
        "{table}.id, {table}.title, substr({table}.body, 1, {PREVIEW_SOURCE_CHARS}), \
         {table}.color, {table}.pinned, {table}.updated_at, {table}.deleted_at, \
         {table}.heading <> ''"
    )
}

fn summary_from_row(row: &Row<'_>) -> rusqlite::Result<NoteSummary> {
    let body: String = row.get(2)?;
    let has_heading: bool = row.get(7)?;
    Ok(NoteSummary {
        id: row.get(0)?,
        title: row.get(1)?,
        preview: derive_preview(&body, has_heading),
        color: row.get(3)?,
        pinned: row.get(4)?,
        updated_at: row.get(5)?,
        deleted_at: row.get(6)?,
    })
}

fn truncate_chars(text: &str, max: usize) -> String {
    text.chars().take(max).collect()
}

/// First non-empty line, trimmed, up to 80 characters; `""` if the body is empty.
pub fn derive_title(body: &str) -> String {
    body.lines()
        .map(str::trim)
        .find(|line| !line.is_empty())
        .map(|line| truncate_chars(line, TITLE_MAX_CHARS))
        .unwrap_or_default()
}

/// The typed heading if there is one, otherwise the first line of the body.
pub fn note_title(heading: &str, body: &str) -> String {
    match heading.trim() {
        "" => derive_title(body),
        heading => truncate_chars(heading, TITLE_MAX_CHARS),
    }
}

/// Body text with collapsed whitespace, up to 140 characters. Without a heading,
/// the first line is the title, so it is skipped.
pub fn derive_preview(body: &str, has_heading: bool) -> String {
    let mut lines = body.lines().skip_while(|line| line.trim().is_empty());
    if !has_heading {
        lines.next();
    }
    let rest: Vec<&str> = lines.flat_map(str::split_whitespace).collect();
    truncate_chars(&rest.join(" "), PREVIEW_MAX_CHARS)
}

fn validate_body(body: &str) -> Result<(), AppError> {
    if body.chars().count() > BODY_MAX_CHARS {
        return Err(AppError::InvalidInput(
            "A nota passou do limite de 100 000 caracteres.",
        ));
    }
    Ok(())
}

fn validate_color(color: Option<&str>) -> Result<(), AppError> {
    match color {
        Some(value) if !STICKER_COLORS.contains(&value) => {
            Err(AppError::InvalidInput("Cor inválida."))
        }
        _ => Ok(()),
    }
}

fn validate_heading(heading: Option<&str>) -> Result<(), AppError> {
    match heading {
        Some(value) if value.chars().count() > HEADING_MAX_CHARS => Err(AppError::InvalidInput(
            "O título passou do limite de 200 caracteres.",
        )),
        _ => Ok(()),
    }
}

fn validate_opacity(opacity: Option<i64>) -> Result<(), AppError> {
    match opacity {
        Some(value) if !OPACITIES.contains(&value) => {
            Err(AppError::InvalidInput("Opacidade inválida."))
        }
        _ => Ok(()),
    }
}

fn validate_limit(limit: Option<i64>) -> Result<i64, AppError> {
    let limit = limit.unwrap_or(LIMIT_DEFAULT);
    if !(1..=LIMIT_MAX).contains(&limit) {
        return Err(AppError::InvalidInput("Limite inválido."));
    }
    Ok(limit)
}

/// Turns the typed text into a literal FTS5 query: each term becomes a quoted phrase
/// (inner quotes doubled) and the last one gets `*` (prefix search while typing).
/// So `"`, `*`, `-`, `NEAR`, `AND`… never become syntax. `None` if no term is left.
pub fn escape_fts_query(query: &str) -> Option<String> {
    // A punctuation-only term makes no unicode61 token: skip it.
    let terms: Vec<String> = query
        .split_whitespace()
        .filter(|term| term.chars().any(char::is_alphanumeric))
        .map(|term| format!("\"{}\"", term.replace('"', "\"\"")))
        .collect();
    if terms.is_empty() {
        return None;
    }
    Some(format!("{}*", terms.join(" ")))
}

pub fn get(conn: &Connection, id: i64) -> Result<Note, AppError> {
    conn.query_row(
        &format!("SELECT {NOTE_COLUMNS} FROM notes WHERE id = ?1"),
        [id],
        note_from_row,
    )
    .optional()?
    .ok_or(AppError::NotFound)
}

/// The active note with the latest `updatedAt`.
pub fn get_last(conn: &Connection) -> Result<Option<Note>, AppError> {
    Ok(conn
        .query_row(
            &format!(
                "SELECT {NOTE_COLUMNS} FROM notes WHERE deleted_at IS NULL \
                 ORDER BY updated_at DESC, id DESC LIMIT 1"
            ),
            [],
            note_from_row,
        )
        .optional()?)
}

/// Creates (`id = None`) or updates. `None` fields keep the current value on update
/// (`invoke` can't tell a missing field from `null`).
pub fn save(conn: &Connection, input: SaveInput<'_>) -> Result<Note, AppError> {
    validate_body(input.body)?;
    validate_heading(input.heading)?;
    validate_color(input.color)?;
    validate_opacity(input.opacity)?;

    let Some(id) = input.id else {
        let heading = input.heading.unwrap_or_default();
        conn.execute(
            &format!(
                "INSERT INTO notes (title, heading, body, color, opacity, created_at, updated_at) \
                 VALUES (?1, ?2, ?3, ?4, ?5, {NOW}, {NOW})"
            ),
            params![
                note_title(heading, input.body),
                heading,
                input.body,
                input.color,
                input.opacity.unwrap_or(100),
            ],
        )?;
        return get(conn, conn.last_insert_rowid());
    };

    let current = get(conn, id)?;
    if current.deleted_at.is_some() {
        return Err(AppError::InvalidInput("Restaure a nota antes de editá-la."));
    }
    let heading = input.heading.unwrap_or(&current.heading);
    let color = input.color.map(str::to_owned).or(current.color.clone());
    let opacity = input.opacity.unwrap_or(current.opacity);
    // No change: keep updatedAt (otherwise a flush without edits would reorder the history).
    if current.body == input.body
        && current.heading == heading
        && current.color == color
        && current.opacity == opacity
    {
        return Ok(current);
    }
    conn.execute(
        &format!(
            "UPDATE notes SET title = ?1, heading = ?2, body = ?3, color = ?4, opacity = ?5, \
             updated_at = {NOW} WHERE id = ?6"
        ),
        params![
            note_title(heading, input.body),
            heading,
            input.body,
            color,
            opacity,
            id
        ],
    )?;
    get(conn, id)
}

/// `active` skips empty notes (empty title = empty or whitespace-only body)
/// and puts pinned notes first. `color` only filters the active scope
/// (ignored in the trash); `None` in the column counts as yellow (the default).
pub fn list(
    conn: &Connection,
    scope: Scope,
    color: Option<&str>,
    sort: Sort,
    limit: Option<i64>,
    offset: Option<i64>,
) -> Result<Vec<NoteSummary>, AppError> {
    validate_color(color)?;
    let limit = validate_limit(limit)?;
    let offset = offset.unwrap_or(0);
    if offset < 0 {
        return Err(AppError::InvalidInput("Offset inválido."));
    }
    let (filter, order) = match scope {
        Scope::Active => (
            "deleted_at IS NULL AND title <> ''",
            format!("pinned DESC, {}", sort.order_sql()),
        ),
        Scope::Trash => ("deleted_at IS NOT NULL", sort.order_sql().to_owned()),
    };
    let by_color = match (scope, color) {
        (Scope::Active, Some("yellow")) => " AND (color = ?3 OR color IS NULL)",
        (Scope::Active, Some(_)) => " AND color = ?3",
        _ => "",
    };
    let sql = format!(
        "SELECT {} FROM notes WHERE {filter}{by_color} \
         ORDER BY {order} LIMIT ?1 OFFSET ?2",
        summary_columns("notes")
    );
    let mut stmt = conn.prepare(&sql)?;
    let rows = if by_color.is_empty() {
        stmt.query_map(params![limit, offset], summary_from_row)?
    } else {
        stmt.query_map(params![limit, offset, color], summary_from_row)?
    };
    Ok(rows.collect::<Result<_, _>>()?)
}

/// Pins or unpins an active note, without touching `updatedAt`.
pub fn set_pinned(conn: &Connection, id: i64, pinned: bool) -> Result<Note, AppError> {
    if get(conn, id)?.deleted_at.is_some() {
        return Err(AppError::InvalidInput("Restaure a nota antes de fixá-la."));
    }
    conn.execute(
        "UPDATE notes SET pinned = ?2 WHERE id = ?1",
        params![id, pinned],
    )?;
    get(conn, id)
}

/// Permanently removes every note in the trash. A single DELETE: SQLite runs it
/// in one implicit transaction, and the FTS triggers keep the index in sync.
pub fn empty_trash(conn: &Connection) -> Result<(), AppError> {
    conn.execute("DELETE FROM notes WHERE deleted_at IS NOT NULL", [])?;
    Ok(())
}

/// FTS5 over title+body, active notes only, by relevance (`bm25`).
pub fn search(
    conn: &Connection,
    query: &str,
    limit: Option<i64>,
) -> Result<Vec<NoteSummary>, AppError> {
    let query = query.trim();
    let length = query.chars().count();
    if length == 0 || length > QUERY_MAX_CHARS {
        return Err(AppError::InvalidInput(
            "A busca precisa ter de 1 a 200 caracteres.",
        ));
    }
    let limit = validate_limit(limit)?;
    let Some(fts_query) = escape_fts_query(query) else {
        return Ok(Vec::new());
    };
    let mut stmt = conn.prepare(&format!(
        "SELECT {} FROM notes_fts JOIN notes ON notes.id = notes_fts.rowid \
         WHERE notes_fts MATCH ?1 AND notes.deleted_at IS NULL AND notes.title <> '' \
         ORDER BY bm25(notes_fts), notes.updated_at DESC LIMIT ?2",
        summary_columns("notes")
    ))?;
    let rows = stmt.query_map(params![fts_query, limit], summary_from_row)?;
    Ok(rows.collect::<Result<_, _>>()?)
}

/// Soft delete. Deleting a note that is already in the trash changes nothing.
pub fn delete(conn: &Connection, id: i64) -> Result<(), AppError> {
    get(conn, id)?;
    conn.execute(
        &format!("UPDATE notes SET deleted_at = {NOW} WHERE id = ?1 AND deleted_at IS NULL"),
        [id],
    )?;
    Ok(())
}

pub fn restore(conn: &Connection, id: i64) -> Result<Note, AppError> {
    get(conn, id)?;
    conn.execute("UPDATE notes SET deleted_at = NULL WHERE id = ?1", [id])?;
    get(conn, id)
}

/// Permanent removal, only for notes in the trash.
pub fn purge(conn: &Connection, id: i64) -> Result<(), AppError> {
    if get(conn, id)?.deleted_at.is_none() {
        return Err(AppError::InvalidInput(
            "Só notas na lixeira podem ser excluídas para sempre.",
        ));
    }
    conn.execute("DELETE FROM notes WHERE id = ?1", [id])?;
    Ok(())
}

